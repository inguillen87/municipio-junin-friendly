export const CONCEPT_GROUPS = Object.freeze({ haber: 'Haber remunerativo', no_remunerativo: 'Haber no remunerativo', asignacion: 'Asignación familiar', descuento: 'Descuento', contribucion: 'Contribución patronal' });
export const GRH_CONCEPTS = Object.freeze(RAW.map(([code, label, group, novelty, uses]) => Object.freeze({ code: String(code), label, group, novelty: novelty === 1, uses })));
const byCode = new Map(GRH_CONCEPTS.map(c => [c.code, c]));
const fold = v => String(v ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
export function conceptInfo(code) { return byCode.get(String(code ?? '').trim().replace(/^0+(?=\d)/, '')) ?? null; }
/** Up to `limit` concepts matching a code prefix or words of the description; novelty concepts and frequent ones first. */
export function searchConcepts(query, { limit = 12, noveltyFirst = true } = {}) {
  const q = fold(query).trim();
  const words = q.split(/\s+/).filter(Boolean);
  const scored = [];
  for (const c of GRH_CONCEPTS) {
    const text = fold(c.label);
    let score;
    if (!q) score = 0;
    else if (c.code === q) score = 1000;
    else if (/^\d+$/.test(q) && c.code.startsWith(q)) score = 500 - c.code.length;
    else if (words.every(w => text.includes(w) || c.code.startsWith(w))) score = 200 + (text.startsWith(words[0]) ? 50 : 0);
    else continue;
    scored.push([score + (noveltyFirst && c.novelty ? 20 : 0) + Math.min(19, Math.log2(1 + c.uses)), c]);
  }
  return scored.sort((a, b) => b[0] - a[0] || Number(a[1].code) - Number(b[1].code)).slice(0, limit).map(x => x[1]);
}
export function conceptLabel(c) { return c ? c.code + ' · ' + c.label + ' · ' + (CONCEPT_GROUPS[c.group] ?? '') + (c.novelty ? ' · por novedad' : '') : ''; }
